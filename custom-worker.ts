// Cloudflare Workers entry (wrangler.jsonc `main`). Wraps the Worker OpenNext
// generates so the app can also answer Cron Triggers.
//
// fetch: handed straight to OpenNext — every page and route works as before.
//
// scheduled: the Workers counterpart of the Vercel cron in vercel.json
// (/api/cron/snapshot at 01:00 UTC). It calls that same route through the
// WORKER_SELF_REFERENCE service binding, with the header the route checks:
// `Authorization: Bearer <CRON_SECRET>`. The route itself is unchanged.
//
// OFF UNLESS CRONS_ENABLED === "true". Vercel's cron is still live during the
// move, and the job must not run on both hosts. The snapshot is idempotent per
// day, so a double run would only overwrite the day's rows — but the switch
// keeps the ownership clear: flip CRONS_ENABLED on Cloudflare in the same step
// that removes the cron from Vercel.

/* eslint-disable @typescript-eslint/ban-ts-comment -- the import below only exists after a Cloudflare build */
// @ts-ignore `.open-next/worker.js` is generated by `opennextjs-cloudflare build`.
import { default as handler } from "./.open-next/worker.js";

type Env = {
  CRONS_ENABLED?: string;
  CRON_SECRET?: string;
  WORKER_SELF_REFERENCE: { fetch(input: string, init?: RequestInit): Promise<Response> };
};

type ScheduledController = { cron: string; scheduledTime: number };

const worker = {
  fetch: handler.fetch,

  async scheduled(controller: ScheduledController, env: Env): Promise<void> {
    if (env.CRONS_ENABLED !== "true") {
      console.log(`cron ${controller.cron}: skipped, CRONS_ENABLED is not "true"`);
      return;
    }
    if (!env.CRON_SECRET) {
      // The route refuses every call while CRON_SECRET is unset, so calling it
      // would only produce a 401. Say why instead.
      throw new Error(`cron ${controller.cron}: CRON_SECRET is not set on this Worker`);
    }

    // The host is never resolved — a service binding goes straight to this
    // Worker — but the URL still needs one.
    const response = await env.WORKER_SELF_REFERENCE.fetch(
      "https://sampark.internal/api/cron/snapshot",
      { headers: { authorization: `Bearer ${env.CRON_SECRET}` } },
    );
    const body = await response.text();
    if (!response.ok) {
      // Throwing marks the invocation failed in the Workers dashboard.
      throw new Error(`cron ${controller.cron}: snapshot returned ${response.status} ${body.slice(0, 200)}`);
    }
    console.log(`cron ${controller.cron}: snapshot ok ${body.slice(0, 200)}`);
  },
};

export default worker;

